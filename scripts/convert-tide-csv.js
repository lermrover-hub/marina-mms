/**
 * convert-tide-csv.js
 * Reads the Ko Samui 2026 tide CSV and generates lib/tide-data-2026-real.ts
 *
 * Usage:
 *   node scripts/convert-tide-csv.js
 */

import { readFileSync, writeFileSync } from "fs"
import { resolve, dirname } from "path"
import { fileURLToPath } from "url"

const __dirname = dirname(fileURLToPath(import.meta.url))

// ── Input CSV path ──────────────────────────────────────────────────────────
const CSV_PATH = resolve(
  "G:/My Drive/02_COMMAND_CENTER06_ARCHIVE_ORIGINAL_FILES/Ocean Rover Marina/Ai doc/GPT tide table/CSV Ocean_Rover_Marina_Quote_Tide_Automation_2026_v2.csv"
)

// ── Output TS path ──────────────────────────────────────────────────────────
const OUT_PATH = resolve(__dirname, "../lib/tide-data-2026-real.ts")

// ── Parse CSV ───────────────────────────────────────────────────────────────
const csv = readFileSync(CSV_PATH, "utf8").replace(/^﻿/, "") // strip BOM
const lines = csv.split(/\r?\n/).filter(Boolean)
const header = lines[0].split(",")

const dateIdx  = header.indexOf("Date")
const hourIdx  = header.indexOf("Hour")
const tideIdx  = header.indexOf("Tide_m")

if (dateIdx < 0 || hourIdx < 0 || tideIdx < 0) {
  throw new Error(`Missing columns. Found: ${header.join(", ")}`)
}

// Build: { "2026-01-01": number[24] }
const lookup = {}
let skipped = 0

for (let i = 1; i < lines.length; i++) {
  const cols = lines[i].split(",")
  const date  = cols[dateIdx]?.trim()
  const hour  = parseInt(cols[hourIdx]?.trim(), 10)
  const tide  = parseFloat(cols[tideIdx]?.trim())

  if (!date || isNaN(hour) || isNaN(tide)) { skipped++; continue }
  if (hour < 0 || hour > 23) { skipped++; continue }

  if (!lookup[date]) lookup[date] = new Array(24).fill(null)
  lookup[date][hour] = tide
}

// Fill any null slots with neighbour interpolation
let filled = 0
for (const date of Object.keys(lookup)) {
  const arr = lookup[date]
  for (let h = 0; h < 24; h++) {
    if (arr[h] === null) {
      // find nearest non-null neighbour
      const prev = arr.slice(0, h).reverse().find((v) => v !== null)
      const next = arr.slice(h + 1).find((v) => v !== null)
      arr[h] = prev ?? next ?? 1.0
      filled++
    }
  }
  // Round to 1 decimal
  lookup[date] = arr.map((v) => Math.round(v * 10) / 10)
}

const dateCount = Object.keys(lookup).length
const dates = Object.keys(lookup).sort()
const firstDate = dates[0]
const lastDate  = dates[dates.length - 1]

console.log(`Parsed ${dateCount} dates (${firstDate} → ${lastDate})`)
console.log(`Skipped rows: ${skipped}, Filled nulls: ${filled}`)

// ── Validate: check for any remaining nulls ──────────────────────────────────
let nullCount = 0
for (const [date, arr] of Object.entries(lookup)) {
  arr.forEach((v, h) => {
    if (v === null) { console.warn(`  NULL: ${date} hour ${h}`); nullCount++ }
  })
}
if (nullCount > 0) console.error(`WARNING: ${nullCount} null values remain`)

// ── Generate TypeScript ──────────────────────────────────────────────────────
const lines_ts = [
  `/**`,
  ` * Ko Samui 2026 Official Tide Data`,
  ` * Source: Ko Samui tide table 2026 PDF (Thai Hydrographic Department)`,
  ` * Station: Ko Samui, Gulf of Thailand (9.5°N 100.06°E)`,
  ` * Chart Datum: Lowest Astronomical Tide (LAT)`,
  ` * All heights in metres above chart datum.`,
  ` *`,
  ` * Auto-generated by scripts/convert-tide-csv.js`,
  ` * DO NOT EDIT MANUALLY — re-run the script to regenerate.`,
  ` *`,
  ` * Coverage: ${firstDate} → ${lastDate} (${dateCount} days, hourly)`,
  ` */`,
  ``,
  `/**`,
  ` * TIDE_2026["YYYY-MM-DD"][hour] = height in metres above chart datum`,
  ` * hour = 0..23`,
  ` */`,
  `export const TIDE_2026: Record<string, number[]> = {`,
]

for (const date of dates) {
  const arr = lookup[date]
  lines_ts.push(`  "${date}": [${arr.join(", ")}],`)
}

lines_ts.push(`}`)
lines_ts.push(``)
lines_ts.push(`/**`)
lines_ts.push(` * Get hourly tide heights for a date string "YYYY-MM-DD".`)
lines_ts.push(` * Falls back to empty array if date not in table.`)
lines_ts.push(` */`)
lines_ts.push(`export function getTideHeightsForDate(dateStr: string): number[] {`)
lines_ts.push(`  return TIDE_2026[dateStr] ?? []`)
lines_ts.push(`}`)
lines_ts.push(``)
lines_ts.push(`/**`)
lines_ts.push(` * Get tide data as { hour, height }[] for a date string "YYYY-MM-DD".`)
lines_ts.push(` */`)
lines_ts.push(`export function getTideDataForDate(dateStr: string): { hour: number; height: number }[] {`)
lines_ts.push(`  const heights = getTideHeightsForDate(dateStr)`)
lines_ts.push(`  return heights.map((height, hour) => ({ hour, height }))`)
lines_ts.push(`}`)
lines_ts.push(``)
lines_ts.push(`/**`)
lines_ts.push(` * Legacy compat: get tide heights by month + day (assumes year 2026).`)
lines_ts.push(` * month = 1..12, day = 1..31`)
lines_ts.push(` */`)
lines_ts.push(`export function getTideHeights2026(month: number, day: number): number[] {`)
lines_ts.push(`  const mm = String(month).padStart(2, "0")`)
lines_ts.push(`  const dd = String(day).padStart(2, "0")`)
lines_ts.push(`  return getTideHeightsForDate(\`2026-\${mm}-\${dd}\`)`)
lines_ts.push(`}`)
lines_ts.push(``)
lines_ts.push(`export function getTideData2026(month: number, day: number): { hour: number; height: number }[] {`)
lines_ts.push(`  return getTideHeights2026(month, day).map((height, hour) => ({ hour, height }))`)
lines_ts.push(`}`)
lines_ts.push(``)
lines_ts.push(`export const MONTH_NAMES = [`)
lines_ts.push(`  "", "January", "February", "March", "April", "May", "June",`)
lines_ts.push(`  "July", "August", "September", "October", "November", "December",`)
lines_ts.push(`]`)
lines_ts.push(``)
lines_ts.push(`export const DAYS_IN_MONTH_2026: Record<number, number> = {`)
lines_ts.push(`  1: 31, 2: 28, 3: 31, 4: 30, 5: 31, 6: 30,`)
lines_ts.push(`  7: 31, 8: 31, 9: 30, 10: 31, 11: 30, 12: 31,`)
lines_ts.push(`}`)
lines_ts.push(``)

writeFileSync(OUT_PATH, lines_ts.join("\n"), "utf8")
console.log(`\nWritten: ${OUT_PATH}`)
console.log(`File size: ${(lines_ts.join("\n").length / 1024).toFixed(1)} KB`)
